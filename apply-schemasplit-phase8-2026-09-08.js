    workstreamRule: 'npveRebuild_* and leanPilot_* → records/npve; libraryTodos_* and every pre-NPVE library batch → records/library; workflowRefactor_*, postPilot_*, docsOperatorsGuide_*, schemasplit_* → records/workflow',
    dateRule: 'record.date when present, else the date in the id, else position (one record: navComponentsOnCompositionsPage, dated 2026-08-31 from the record before it; the only migration note)',
