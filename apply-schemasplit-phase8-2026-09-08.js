// verifies it against the baseline tag instead of copying again. Finalized by finalize-schemasplit-phase8-2026-09-08.js.
const fs = require('fs');
const { execFileSync } = require('child_process');
const store = require('./scripts/schema/lib');

const ID = 'schemasplit_phase8_2026-09-08';
const DIR = 'figma-export/schema-split-phase8-2026-09-08';
const BACKUP = 'design-system-schema.backup-2026-09-08-pre-schema-split.json';
const TAG = 'schema-split-baseline-2026-09-08';
const PREVIOUS = ['postPilot_merge_2026-09-08', 'npveRebuild_moduleChipFix_2026-09-08'];

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).trim();
if (git('branch', '--show-current') !== 'master') throw new Error('expected master');
const tagCommit = git('rev-parse', '--short', `${TAG}^{commit}`);
if (!fs.existsSync(BACKUP)) throw new Error(`backup missing: ${BACKUP}`);
const backupSha = store.sha256(fs.readFileSync(BACKUP));
const tagSha = store.sha256(git('show', `${TAG}:design-system-schema.json`));
if (backupSha !== tagSha) throw new Error('backup does not match the schema at the baseline tag');
const baseline = JSON.parse(fs.readFileSync(`${DIR}/baseline-counts.json`, 'utf8'));
const reconciliation = JSON.parse(fs.readFileSync(`${DIR}/reconciliation.json`, 'utf8'));
if (reconciliation.result !== 'PASS' || !reconciliation.byteIdentical) throw new Error('step 3 reconciliation did not pass; the batch stops');
const migrationCommit = git('log', '-1', '--format=%h', '--', 'scripts/schema/migrate-split.js');

